#!/usr/bin/env python3
"""Generate bounded per-program gains from audit-program-levels --raw output.

Uses activity-gated RMS, four keys, velocity 100 and factory FX output. Distinct category
anchors preserve percussion attacks and bass/lead balance. Does not normalize
samples, alter velocity layers, compress transients, or boost near-silent noise.
"""
import argparse
import csv
import hashlib
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = {"PIANO": -34, "E.PIANO": -34, "ORGAN": -33, "BELL": -38,
          "STRINGS": -33, "BRASS": -33, "SYNTH LEAD": -33, "SYNTH PAD": -33,
          "GUITAR": -36, "BASS": -33, "DRUM/SFX": -36}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("measurements", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "src/core/voice/ProgramLevels.h")
    parser.add_argument("--stress", type=Path, action="append", default=[],
                        help="Complete chord audit TSV, measured using --reference-gains")
    parser.add_argument("--reference-gains", type=Path)
    args = parser.parse_args()
    programs = json.loads((ROOT / "assets/program-library/FactoryPrograms.json").read_text())
    categories = {p[0]: p[2] for p in programs}
    rows = list(csv.DictReader(args.measurements.open(), delimiter="\t"))
    if {r["id"] for r in rows} != set(categories) - {"EX"}:
        raise ValueError("Measurements must cover the complete factory bank")
    caps = {}
    if args.stress:
        if not args.reference_gains:
            raise ValueError("Stress measurements require their original gain table")
        reference = {key: float(db) for key, db in re.findall(
            r'\{"([^"]+)", ([-\d.]+)f\}', args.reference_gains.read_text())}
        for path in args.stress:
            stress = list(csv.DictReader(path.open(), delimiter="\t"))
            if {r["id"] for r in stress} != set(categories) - {"EX"}:
                raise ValueError("Each stress audit must cover every program")
            for r in stress:
                peak = float(r["peak"])
                if not math.isfinite(peak) or peak < 0:
                    raise ValueError("Invalid stress peak")
                if peak > 1e-12:
                    cap = reference[r["id"]] + 20 * math.log10(.85 / peak)
                    caps[r["id"]] = min(caps.get(r["id"], math.inf), cap)
    values = []
    for r in rows:
        peak, rms = float(r["peak_db"]), float(r["active_rms_db"])
        category = categories[r["id"]]
        # Low SFX/noise requires a separate diagnosis, never a 60 dB boost.
        gain = 0 if rms < -65 else min(18, TARGET[category] - rms, -18 - peak)
        gain = max(-36, math.floor(min(gain, caps.get(r["id"], math.inf)) * 2) / 2)
        values.append((r["id"], gain))
    lines = ["#pragma once", "#include <algorithm>", "#include <array>", "#include <cmath>",
             "#include <string_view>", "", "namespace segrand {",
             "// Generated by tools/audio/calibrate_program_levels.py; factory FX, four keys, velocity 100.",
             "// Static gains retain dynamics. Peak cap -18 dBFS leaves chord/velocity headroom.",
             f"// Measurement SHA256: {hashlib.sha256(args.measurements.read_bytes()).hexdigest()}",
             "struct ProgramLevel { std::string_view id; float db; };",
             f"inline constexpr std::array<ProgramLevel, {len(values)}> kProgramLevels{{{{"]
    for path in args.stress:
        lines.insert(10, f"// Chord audit SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}")
    lines += [f'    {{"{key}", {gain:.1f}f}},' for key, gain in sorted(values)]
    lines += ["}};", "inline double ProgramLevelGain(std::string_view id) noexcept {",
              "  const auto it = std::lower_bound(kProgramLevels.begin(), kProgramLevels.end(), id,",
              "      [](const ProgramLevel &entry, std::string_view key) { return entry.id < key; });",
              "  return it != kProgramLevels.end() && it->id == id ? std::pow(10., it->db / 20.) : 1.;",
              "}", "} // namespace segrand", ""]
    args.output.write_text("\n".join(lines))
    print(f"Calibrated {len(values)} programs; gains {min(g for _,g in values):g}..{max(g for _,g in values):g} dB")

if __name__ == "__main__":
    main()
