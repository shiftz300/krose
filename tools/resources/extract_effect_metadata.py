#!/usr/bin/env python3
"""Extract checked KROSS 2 v1.2.4 effect parameter descriptors (no DSP code)."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

SHA = '3005f0eca3f3772bcb810c526ceebb15562747d3cdcdf5d20faae4a539520c54'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('firmware',type=Path)
    parser.add_argument('output',type=Path)
    args=parser.parse_args()
    data=args.firmware.read_bytes()
    if hashlib.sha256(data).hexdigest()!=SHA: raise ValueError('Unexpected firmware version')
    def u32(at): return struct.unpack_from('<I',data,at)[0]
    def ptr(at):
        value=u32(at)-0xc0000000
        if not 0<=value<len(data): raise ValueError('Invalid pointer')
        return value
    def text(at): return json.dumps(data[at:data.index(0,at)].decode('ascii'))
    fields=[];definitions=[]
    for effect in range(135):
        definition=ptr(0x336d6c+4*effect)
        count,code_count=struct.unpack_from('<HH',data,definition+28)
        start=len(fields); table=ptr(definition+36)
        for i in range(count):
            p=ptr(table+4*i); descriptor=ptr(p+8)
            kind,_,shift,width=struct.unpack_from('<4B',data,descriptor)
            low,high=struct.unpack_from('<ii',data,descriptor+8)
            fields.append(f'    {{{text(ptr(p+12))}, {u32(p+16)&255}, {kind}, {shift}, {width}, {low}, {high}, 0x{max(0,u32(p+20)-0xc0000000):x}}},')
        definitions.append(f'    {{{text(ptr(definition))}, {start}, {count}, {1+(code_count>124)}}},')
    out=['#pragma once','#include <array>','#include <cstdint>','namespace segrand::effect_data {',
         '// Generated by extract_effect_metadata.py from the version-locked official firmware.',
         f'// Firmware SHA256: {SHA}',
         'struct Field { const char *label; uint8_t offset, kind, shift, width; int min, max; uint32_t display; };',
         'struct Effect { const char *name; uint16_t first, count; uint8_t units; };',
         f'inline constexpr std::array<Field,{len(fields)}> kFields{{{{',*fields,'}};',
         'inline constexpr std::array<Effect,135> kEffects{{{',*definitions,'}};',
         '} // namespace segrand::effect_data','']
    out[out.index('inline constexpr std::array<Effect,135> kEffects{{{')]='inline constexpr std::array<Effect,135> kEffects{{'
    args.output.write_text('\n'.join(out))
    print('Extracted',len(fields),'parameter descriptors; 135 effect definitions')
if __name__=='__main__':main()
