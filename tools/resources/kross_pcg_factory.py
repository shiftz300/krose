"""Extract KROSS 2 legacy Program mapping and restore its onboard PCG waveforms."""

import argparse
import hashlib
import mmap
from pathlib import Path
import struct

FIRMWARE_HASH = '3005f0eca3f3772bcb810c526ceebb15562747d3cdcdf5d20faae4a539520c54'
ROM_HASH = 'c9d4c9b4dd0f915b45a553e6b66d2cab7e51b80f4b2189fb6db4d91b1ccc94a5'
FUTURE_SYNTH_HASH = '4bb3dd70b0cf8276fb48cd1afda23350181df69825dd3add82c4f0cecba79baa'
ROM_SAMPLES = 4068
DESCRIPTORS = 24 + 224 * 4 + 256 * 2 + 129 * 2 + 512


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_verified(path, expected):
    data = path.read_bytes()
    require(hashlib.sha256(data).hexdigest() == expected, f'Unexpected input: {path}')
    return data


def read_tables(firmware):
    # 0x2a6024 only visits ROM banks (0/1). 0x2a62dc matches both
    # bank and number, copies the destination pair, or returns the input.
    table, count = struct.unpack_from('<II', firmware, 0x2a6044)
    require((table, count) == (0xc0454fac, 410), 'Unexpected Program remap table')
    mapping = {}
    for row in range(count):
        bank, number, new_bank, new_number = struct.unpack_from(
            '<4I', firmware, table - 0xc0000000 + row * 16)
        mapping.setdefault((bank, number), (new_bank, new_number))
    mono = [mapping.get((0, number), (0, number)) for number in range(421)]
    stereo = [mapping.get((1, number), (1, number)) for number in range(6)]
    require(len(mapping) == count and all(bank == 0 for bank, _ in mono), 'Invalid remap entries')

    multisamples = [struct.unpack_from('<HBB24s', firmware, 0x48f5cc + 28 * i)
                    for i in range(496)]
    pairs = [i for i, (_, _, _, name) in enumerate(multisamples[:-1])
             if name.rstrip().endswith(b'-L') and
             multisamples[i + 1][3].rstrip() == name.rstrip()[:-1] + b'R']
    require(len(pairs) == 7, 'Unexpected stereo multisample list')
    starts = [first for first, _, _, _ in multisamples]
    zones = []
    for first, count, _, _ in multisamples:
        require(first == len(zones) and count > 0, 'Invalid multisample range')
        last = -1
        for i in range(first, first + count):
            sample, _, top, root, flags, fine = struct.unpack_from(
                '<HBBBBh', firmware, 0x492c28 + 20 * i)
            require(sample < ROM_SAMPLES and last < top <= 127 and root <= 127,
                    'Invalid ROM key zone')
            zones.append((sample, fine, top, root, flags & 1))
            last = top
    require(len(zones) == 5568, 'Unexpected ROM key zone count')
    return [number for _, number in mono], stereo, pairs, starts + [len(zones)], zones


def write_header(path, tables):
    mono, stereo, pairs, starts, zones = tables
    with path.open('w', newline='\n') as out:
        out.write('''#pragma once
#include <array>
#include <cstdint>

namespace segrand::pcg {
// KROSS 2 v1.2.4. Generated by tools/resources/kross_pcg_factory.py.
struct Multisample {
  uint8_t bank;
  uint16_t number;
};

struct RomZone {
  uint16_t sample;
  int16_t fine;
  uint8_t top, root;
  bool fixed;
};
''')
        out.write(f'inline constexpr unsigned kRomSampleCount = {ROM_SAMPLES};\n\n')
        for name, kind, values, width in (
            ('kMono', 'uint16_t', mono, 12),
            ('kStereo', 'Multisample', stereo, 6),
            ('kFactoryStereo', 'uint16_t', pairs, 7),
            ('kRomStarts', 'uint16_t', starts, 12),
            ('kRomZones', 'RomZone', zones, 3),
        ):
            out.write(f'inline constexpr std::array<{kind}, {len(values)}> {name} = {{{{\n')
            for i in range(0, len(values), width):
                row = values[i:i + width]
                out.write('    ' + ', '.join(
                    '{' + ', '.join(map(str, item)) + '}' if isinstance(item, tuple) else str(item)
                    for item in row) + ',\n')
            out.write('}};\n\n')
        out.write('} // namespace segrand::pcg\n')


def future_synth_samples(data):
    count, = struct.unpack_from('<I', data, 0x9c)
    prm_size, = struct.unpack_from('<I', data, 200)
    pcm = 208 + prm_size
    size, = struct.unpack_from('<I', data, pcm + 8)
    require(count == 195 and data[pcm:pcm + 4] == b'PCM1' and pcm + 16 + size <= len(data),
            'Unexpected Future Synth sample layout')
    return {40000 + i: (data[208 + i * 64:208 + (i + 1) * 64], data, pcm + 16, size)
            for i in range(count)}


def future_synth_regions(data, indices):
    # KROSS 88 MB Extra Voice Name List, Electrik Kit (pp. 8–9).
    # These exact KG4 references occur in the official KEP as encoded bank 12.
    references = ((45, 1, 7, b'SD-FPop'), (83, 0, 34, b'Hit-Cinema 1'),
                  (96, 0, 17, b'Voice-Boom Hi'), (96, 1, 16, b'Voice-Boom Lo'))
    counts = struct.unpack_from('<4I', data, 0x9c)
    drum_table = 208 + counts[0] * 64 + counts[1] * 20 + counts[2] * 28
    require(counts[3] == 45, 'Unexpected KG4 drum catalog')
    kit_offset = 8468520 + 8728
    kit = data[kit_offset:kit_offset + 8728]
    require(kit[:24].strip() == b'Electrik Kit', 'Unexpected EXPCM004 drum kit')
    rows = {}
    for note, slot, number, name in references:
        key = kit[24 + note * 68:24 + (note + 1) * 68]
        layer = key[12 * slot:12 * (slot + 1)]
        require(key[65] & 5 == 5 and layer[0] & 1 and layer[1] == 12 and
                struct.unpack_from('<H', layer, 2)[0] == number, 'Unexpected Electrik layer')
        drum = data[drum_table + number * 32:drum_table + (number + 1) * 32]
        sample_id, bank = struct.unpack_from('<HB', drum)
        require(bank == 5 and drum[4:28].rstrip(b' \0') == name, 'KG4 sample mismatch')
        waves = 40000 + sample_id
        bottom, fade_in, curve_in = key[48 + 4 * slot:51 + 4 * slot]
        upper = key[48] - 1 if slot else 127
        fade_bottom, fade_out, curve_out = key[48:51] if slot else (0, 0, 0)
        ranges = [(bottom, upper)] if bottom <= upper else []
        if fade_out:
            ranges.append((fade_bottom, min(127, fade_bottom + fade_out - 1)))
        low = max(1, min(a for a, _ in ranges))
        high = max(b for _, b in ranges)
        level, reverse, coarse, fine = struct.unpack_from('<bBbb', layer, 4)
        require(not reverse & 128, 'Unexpected reversed Electrik sample')
        rows[(note, slot)] = struct.pack(
            '<7IiIi5If8i', indices[waves], 0xffffffff, note, note, low, high, 60, 0, 60, 0,
            0, 127, key[60], key[64], 8, 2 ** ((level - 99) / 50), coarse, fine,
            slot, fade_in, curve_in & 3, fade_bottom, fade_out, curve_out & 3)
    return rows


def repair_regions(bank, records, regions, programs, data, indices):
    program_start = records + regions * 96
    payload = program_start + programs * 2232
    zone_data = bank[records:program_start]
    program_data = bytearray(bank[program_start:payload])
    if data is None:
        return zone_data, program_data, 0
    target = next((p for p in range(0, len(program_data), 2232)
                   if program_data[p:p + 16].rstrip(b'\0') == b'EXPCM004:043'), None)
    require(target is not None, 'Electric Beats Kit is missing from the bank')
    first, count = struct.unpack_from('<II', program_data, target + 84)
    raw = program_data[target + 92:target + 2232]
    require(first + count <= regions and raw[0x508] & 7 == 2 and
            raw[0x566:0x568] == b'\x2b\0' and not any(raw[0x5dc:0x5de]),
            'Unexpected Electric Beats Program')
    rows = future_synth_regions(data, indices)
    for pos in range(first * 96, (first + count) * 96, 96):
        note, = struct.unpack_from('<I', zone_data, pos + 8)
        slot, = struct.unpack_from('<I', zone_data, pos + 72)
        expected = rows.pop((note, slot), None)
        if expected is not None:
            require(zone_data[pos:pos + 96] == expected, 'Inconsistent restored Electrik layer')
    appended = len(rows)
    insertion = (first + count) * 96
    zone_data = zone_data[:insertion] + b''.join(rows.values()) + zone_data[insertion:]
    struct.pack_into('<I', program_data, target + 88, count + appended)
    for pos in range(target + 2232 + 84, len(program_data), 2232):
        start, = struct.unpack_from('<I', program_data, pos)
        require(start >= first + count, 'Invalid Program region ordering')
        struct.pack_into('<I', program_data, pos, start + appended)
    return zone_data, program_data, appended


def restore_bank(source, output, firmware, rom, future_synth):
    with source.open('rb') as stream, mmap.mmap(stream.fileno(), 0, access=mmap.ACCESS_READ) as bank:
        require(bank[:12] == b'KRPRG003\x03\0\0\0', 'Expected a native unsplit KRPRG003 bank')
        require(bank[DESCRIPTORS - 512:DESCRIPTORS] == firmware[0x3fd180:0x3fd380],
                'Factory bank has a different PCM decoder LUT')
        count, regions, programs = struct.unpack_from('<III', bank, 12)
        records = DESCRIPTORS + count * 40
        payload = records + regions * 96 + programs * 2232
        require(0 < count <= 8192 and payload < len(bank), 'Invalid Factory bank tables')
        indices = {struct.unpack_from('<I', bank, pos)[0]: i
                   for i, pos in enumerate(range(DESCRIPTORS, records, 40))}
        require(len(indices) == count, 'Duplicate Factory sample IDs')
        additional = future_synth_samples(future_synth) if future_synth is not None else {}
        missing = sorted((set(range(ROM_SAMPLES)) | additional.keys()) - indices.keys())
        require(count + len(missing) <= 8192, 'Too many samples in Factory bank')
        indices.update((sample, count + i) for i, sample in enumerate(missing))
        zone_data, program_data, added_regions = repair_regions(
            bank, records, regions, programs, future_synth, indices)
        header = bytearray(bank[:records])
        struct.pack_into('<II', header, 12, count + len(missing), regions + added_regions)
        shift = len(missing) * 40 + added_regions * 96
        next_offset = len(bank) + shift
        for pos in range(DESCRIPTORS, records, 40):
            offset, = struct.unpack_from('<Q', bank, pos + 24)
            struct.pack_into('<Q', header, pos + 24, offset + shift)

        # Append to preserve all existing region and Concert sample indexes.
        waveforms = []
        for sample in missing:
            if sample < ROM_SAMPLES:
                pos = 0x410abc + sample * 64
                descriptor, source_data, base, length = firmware[pos:pos + 64], rom, 0, len(rom)
            else:
                descriptor, source_data, base, length = additional[sample]
            flags = descriptor[7]
            pitch, = struct.unpack_from('<h', descriptor)
            a1, a2 = struct.unpack_from('<hh', descriptor, 8)
            start, _, loop, end = struct.unpack_from('<4I', descriptor, 12)
            unit = 1 if flags & 1 else 2
            require(start <= loop <= end and (end + 1) * unit <= length and
                    (sample < ROM_SAMPLES or unit == 1),
                    f'Invalid original descriptor {sample}')
            header += struct.pack('<5IiQhhI', sample, end - start + 1, loop - start,
                                  end - start, flags, pitch, next_offset, a1, a2, unit)
            waveforms.append(memoryview(source_data)[base + start * unit:base + (end + 1) * unit])
            next_offset += len(waveforms[-1])

        with output.open('wb') as out:
            out.write(header)
            out.write(zone_data)
            out.write(program_data)
            for offset in range(payload, len(bank), 8 * 1024 * 1024):
                out.write(bank[offset:offset + 8 * 1024 * 1024])
            for waveform in waveforms:
                out.write(waveform)
        print(f'Added {len(missing)} original samples and {added_regions} drum regions '
              f'({next_offset - len(bank):,} bytes)')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('firmware', type=Path)
    parser.add_argument('rom', type=Path)
    parser.add_argument('source_bank', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--future-synth', type=Path, help='Verified decoded EXPCM004 bank')
    args = parser.parse_args()
    output_bank = args.output / 'Factory.samples'
    require(output_bank.resolve() != args.source_bank.resolve(), 'Use a separate staging directory')
    firmware = read_verified(args.firmware, FIRMWARE_HASH)
    rom = read_verified(args.rom, ROM_HASH)
    tables = read_tables(firmware)
    future_synth = read_verified(args.future_synth, FUTURE_SYNTH_HASH) if args.future_synth else None
    args.output.mkdir(parents=True, exist_ok=True)
    restore_bank(args.source_bank, output_bank, firmware, rom, future_synth)
    write_header(args.output / 'KrossPcgMap.h', tables)


if __name__ == '__main__':
    main()
